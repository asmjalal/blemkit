// Copies lib/runtime/exported/*.dart into lib/generators/runtime_sources.g.dart
// so the exporter can write them into generated projects.
//
//   dart run tool/embed_runtime.dart
//
// test/generators/runtime_sources_test.dart fails when this is out of date.
import 'dart:io';

void main() {
  final dir = Directory('lib/runtime/exported');
  final files = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.dart')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_runtime.dart from lib/runtime/exported. Do not edit.')
    ..writeln('// ignore_for_file: prefer_single_quotes')
    ..writeln()
    ..writeln('const Map<String, String> kRuntimeSources = {');
  for (final file in files) {
    final source = file.readAsStringSync();
    if (source.contains("'''")) {
      stderr.writeln('${file.path} contains a triple quote and cannot be embedded.');
      exit(1);
    }
    out.writeln("  '${file.uri.pathSegments.last}': r'''$source''',");
  }
  out.writeln('};');
  File('lib/generators/runtime_sources.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Embedded ${files.length} runtime files.');
}
